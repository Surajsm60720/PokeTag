/** Resolve a Gen 6 met-location / location index to a display name. */
export function gen6LocationName(locationId: number): string {
  if (locationId <= 0) return "";
  return GEN6[locationId] ?? `Location #${locationId}`;
}

/**
 * Map a Situation.M zonedata entry to a location index.
 * XY uses the zone table; ORAS Situation.M already matches location indexes
 * for common areas (PKHeX IsMetLocation6AO range), so pass through when named.
 */
export function gen6LocationIdFromZone(
  zoneId: number,
  game: "xy" | "oras"
): number {
  if (zoneId <= 0) return 0;
  if (game === "xy") {
    return XY_ZONE_TO_LOCATION[zoneId] ?? 0;
  }
  // ORAS: prefer direct location-index lookup when the id is named.
  if (GEN6[zoneId]) return zoneId;
  return 0;
}

/** Resolve Situation.M for the active game to a display name + location index. */
export function gen6SituationLocation(
  zoneId: number,
  game: "xy" | "oras"
): { locationId: number; name: string } {
  const locationId = gen6LocationIdFromZone(zoneId, game);
  return { locationId, name: gen6LocationName(locationId) };
}
