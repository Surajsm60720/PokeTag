/** Place name for a HeartGold or SoulSilver map id. Unknown ids stay numbered. */
export function hgssMapName(mapId: number): string {
  if (mapId > 0 && mapId < HGSS_MAPS.length && HGSS_MAPS[mapId]) {
    return HGSS_MAPS[mapId]!;
  }
  return mapId ? `Map ${mapId}` : "";
}
