type MonInput = Omit<ParsedPokemon, "slot" | "friendship" | "moveDetails" | "heldItemId" | "ball" | "metLevel" | "metLocation" | "metLocationId" | "originGame" | "originKind" | "caughtAt" | "otName"> & {
  friendship?: number;
  moveDetails?: ParsedPokemon["moveDetails"];
  heldItemId?: number | null;
  ball?: string | null;
  metLevel?: number | null;
  metLocation?: string | null;
  metLocationId?: number | null;
  originGame?: string | null;
  originKind?: ParsedPokemon["originKind"];
  caughtAt?: string | null;
  otName?: string;
};

function mon(slot: number, input: MonInput): ParsedPokemon {
  return withPokemonDefaults({
    slot,
    friendship: input.friendship ?? 120,
    ...input,
  });
}

