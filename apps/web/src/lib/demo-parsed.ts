function fillParty(mons: MonInput[], extras: MonInput[] = []): ParsedPokemon[] {
  const seen = new Set<number>();
  const padded: MonInput[] = [];
  for (const m of [...mons, ...extras, ...PARTY_PAD]) {
    if (padded.length >= 6) break;
    if (seen.has(m.speciesId)) continue;
    seen.add(m.speciesId);
    padded.push(m);
  }
  return padded.slice(0, 6).map((m, i) => mon(i, m));
}

function badges(names: string[], earnedCount: number): ParsedBadge[] {
  return names.map((name, i) => ({
    id: `badge-${i + 1}`,
    name,
    earned: i < earnedCount,
  }));
}

function box(
  index: number,
  name: string,
  wallpaper: string,
  occupants: Array<MonInput | null>
): ParsedBox {
  const pokemon: Array<ParsedPokemon | null> = Array.from(
    { length: 30 },
    () => null
  );
  occupants.slice(0, 30).forEach((m, i) => {
    pokemon[i] = m ? mon(i, m) : null;
  });
  return { index, name, wallpaper, pokemon };
}

function dexStrip(
  ownedNames: string[],
  seenExtra: string[],
  regionalTotal: number,
  startId: number
): ParsedDex {
  const entries: ParsedDexEntry[] = [];
  let id = startId;
  for (const name of ownedNames) {
    entries.push({
      speciesId: id++,
      speciesName: name,
      seen: true,
      owned: true,
    });
  }
  for (const name of seenExtra) {
    entries.push({
      speciesId: id++,
      speciesName: name,
      seen: true,
      owned: false,
    });
  }
  // pad a few unseen silhouettes
  for (let i = 0; i < 6; i++) {
    entries.push({
      speciesId: id++,
      speciesName: `????`,
      seen: false,
      owned: false,
    });
  }
  const owned = ownedNames.length;
  const seen = owned + seenExtra.length;
  return { seen, owned, regionalTotal, entries };
}

