export function hasDemoSnapshot(gameVersion: string): boolean {
  return Boolean(SPECS[gameVersion]);
}

export function buildDemoSnapshot(
  gameVersion: string,
  versionId: string
): ParsedSnapshot | null {
  const spec = SPECS[gameVersion];
  if (!spec) return null;

  const party = fillParty(spec.party, spec.boxExtras);
  const boxes = [
    box(0, spec.boxName, spec.wallpaper, [
      ...spec.boxExtras,
      null,
      null,
      party[0]
        ? {
            ...party[0],
            nickname: `${party[0].nickname.slice(0, 6)}*`,
            level: Math.max(5, party[0].level - 20),
          }
        : null,
    ]),
    box(1, "BOX 2", "plain", [null, null, null]),
  ];

  return {
    versionId,
    gameVersion,
    parserVersion: "demo-1.0",
    isDemo: true,
    trainer: spec.trainer,
    party,
    boxes,
    dex: dexStrip(
      spec.dexOwned,
      spec.dexSeen,
      spec.dexTotal,
      spec.dexStartId
    ),
    badges: badges(spec.badgeNames, spec.badgesEarned),
    playTimeSeconds: spec.playTimeSeconds,
    location: spec.location,
    locationMapId: spec.locationMapId,
    inventory: emptyInventory(),
    progress: emptyProgress("Demo snapshot — no story flags."),
  };
}
